#!/usr/bin/env node
// Regenerates the translation status in PROGRESS.md (between the i18n:status markers):
//   - tool × locale matrix from the frontmatter of src/content/tools/<locale>/<id>.md
//   - about/privacy (src/content/pages) and contact (the "contact" UI strings)
//   - UI string coverage per namespace group (src/i18n/ui/<locale>.ts)
// A tool page is indexed in a locale only when its Markdown is complete AND the chrome strings
// and the tool's widget namespace are translated (src/i18n/indexing.ts decides; this is a report).
//
//   node scripts/i18n-status.mjs           update PROGRESS.md
//   node scripts/i18n-status.mjs --print   print the matrix only
import { existsSync } from 'node:fs';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { load as yamlLoad } from 'js-yaml';

const CONTENT = 'src/content/tools';
const LOCALES = ['es', 'pt', 'fr', 'de', 'hi', 'ja'];
const PROGRESS = 'PROGRESS.md';
const START = '<!-- i18n:status:start -->';
const END = '<!-- i18n:status:end -->';

async function frontmatter(file) {
  const text = await readFile(file, 'utf8');
  const match = text.match(/^---\n([\s\S]*?)\n---/);
  if (!match) throw new Error(`${file}: missing frontmatter`);
  return yamlLoad(match[1]);
}

// UI strings: chrome vs. widget namespaces, read from src/i18n/widgets.ts (a report, so a regex is enough).
const { en } = await import(path.resolve('src/i18n/ui/en.ts'));
const catalogs = Object.fromEntries(await Promise.all(LOCALES.map(async (locale) => [locale, (await import(path.resolve(`src/i18n/ui/${locale}.ts`)))[locale]])));
const widgetsSource = await readFile('src/i18n/widgets.ts', 'utf8');
const byToolBlock = widgetsSource.slice(widgetsSource.indexOf('const byTool'), widgetsSource.indexOf('};', widgetsSource.indexOf('const byTool')));
const widgetNamespaces = new Set(['screen', ...[...byToolBlock.matchAll(/\['([a-z_]+)'\]/g)].map((m) => m[1])]);
const cardVisible = new Set([...(widgetsSource.match(/cardVisible = new Set\(\[([^\]]*)\]/)?.[1] ?? '').matchAll(/'([a-z_]+)'/g)].map((m) => m[1]));
const pageOnly = new Set(['contact', 'not_found', 'server_error']);
const namespaceOf = (key) => key.slice(0, key.indexOf('.'));
const chromeKeys = Object.keys(en).filter((key) => {
  const ns = namespaceOf(key);
  return !pageOnly.has(ns) && (!widgetNamespaces.has(ns) || cardVisible.has(ns));
});
const coverage = (locale, keys) => {
  const done = keys.filter((key) => catalogs[locale][key]?.trim()).length;
  return done === keys.length ? '✅' : `${done}/${keys.length}`;
};
const keysOf = (ns) => Object.keys(en).filter((key) => namespaceOf(key) === ns);
const uiRows = [
  `| chrome (${chromeKeys.length} strings, every page) | ${LOCALES.map((locale) => coverage(locale, chromeKeys)).join(' | ')} |`,
  ...[...pageOnly].map((ns) => `| ${ns} | ${LOCALES.map((locale) => coverage(locale, keysOf(ns))).join(' | ')} |`),
  ...[...widgetNamespaces].filter((ns) => !cardVisible.has(ns)).sort().map((ns) => `| ${ns} | ${LOCALES.map((locale) => coverage(locale, keysOf(ns))).join(' | ')} |`),
];
const pageRows = [];
for (const page of ['about', 'privacy']) {
  const cells = [];
  for (const locale of LOCALES) {
    const file = path.join('src/content/pages', locale, `${page}.md`);
    cells.push(existsSync(file) && (await frontmatter(file)).status === 'complete' ? '✅' : existsSync(file) ? 'draft' : '—');
  }
  pageRows.push(`| ${page} | ${cells.join(' | ')} |`);
}
pageRows.push(`| contact | ${LOCALES.map((locale) => coverage(locale, keysOf('contact'))).join(' | ')} |`);

const ids = (await readdir(path.join(CONTENT, 'en'))).filter((name) => name.endsWith('.md')).map((name) => name.slice(0, -3)).sort();
const rows = [];
const totals = Object.fromEntries(LOCALES.map((locale) => [locale, 0]));

for (const id of ids) {
  const cells = [];
  for (const locale of LOCALES) {
    const file = path.join(CONTENT, locale, `${id}.md`);
    if (!existsSync(file)) {
      cells.push('—');
      continue;
    }
    const { status } = await frontmatter(file);
    if (status === 'complete') totals[locale]++;
    cells.push(status === 'complete' ? '✅' : 'draft');
  }
  rows.push(`| ${id} | ${cells.join(' | ')} |`);
}

const table = [
  `Generated by \`npm run i18n:status\` on ${new Date().toISOString().slice(0, 10)}. ✅ translated and stamped · draft (noindex) · — no file. A tool page is indexed when its Markdown is ✅ and its widget strings (last table) are ✅.`,
  '',
  `| tool (${ids.length}) | ${LOCALES.join(' | ')} |`,
  `|---|${LOCALES.map(() => '---').join('|')}|`,
  ...rows,
  `| **complete** | ${LOCALES.map((locale) => `${totals[locale]}/${ids.length}`).join(' | ')} |`,
  '',
  `| page | ${LOCALES.join(' | ')} |`,
  `|---|${LOCALES.map(() => '---').join('|')}|`,
  ...pageRows,
  '',
  `| UI strings (card-visible widgets count as chrome) | ${LOCALES.join(' | ')} |`,
  `|---|${LOCALES.map(() => '---').join('|')}|`,
  ...uiRows,
].join('\n');

if (process.argv.includes('--print')) {
  console.log(table);
} else {
  const progress = await readFile(PROGRESS, 'utf8');
  const start = progress.indexOf(START);
  const end = progress.indexOf(END);
  if (start === -1 || end === -1) throw new Error(`${PROGRESS}: status markers not found`);
  await writeFile(PROGRESS, `${progress.slice(0, start + START.length)}\n${table}\n${progress.slice(end)}`);
  console.log(`updated ${PROGRESS}: ${LOCALES.map((locale) => `${locale} ${totals[locale]}/${ids.length}`).join(', ')}`);
}
